/**
 * Query behaviour on a real, desktop-maintained-format library at representative scale: the library
 * generated by `assets/calibre-extended/generate.py` (not stored in the repository). Expectations are
 * computed by plain SQL on the same file, so no number is hard-coded. Skipped unless the instrumentation
 * argument `extendedLibraryDb` names a readable `metadata.db` on the device, for example:
 *
 *     adb push <library>/metadata.db /data/local/tmp/extended-metadata.db
 *     -e extendedLibraryDb /data/local/tmp/extended-metadata.db
 *
 * The file is read through the shell, so it needs no app permission, and only copies are imported.
 */
@RunWith(AndroidJUnit4::class)
class ExtendedLibraryQueryTest {
    private lateinit var context: Context
    private lateinit var root: File
    private lateinit var databaseName: String
    private lateinit var database: ApplicationStateDatabase
    private lateinit var metadata: MetadataRepository
    private lateinit var service: LibraryQueryService
    private var oracle: SQLiteDatabase? = null
    private var importCopy: File? = null
    private val collator = Collator.getInstance(Locale.ROOT).apply { strength = Collator.TERTIARY }

    @Before
    fun setUp() {
        context = InstrumentationRegistry.getInstrumentation().targetContext
        root = File(context.cacheDir, "extended-query-${UUID.randomUUID()}").apply { mkdirs() }
        databaseName = "extended-query-${UUID.randomUUID()}.db"
        database = ApplicationStateDatabase(context, databaseName)
        val files = File(root, "files").apply { mkdirs() }
        val state = ApplicationStateRepository(database, PrivateBookFiles(files), Dispatchers.IO)
        metadata = MetadataRepository(database, state, File(root, "metadata"), Dispatchers.IO)
        service = LibraryQueryService(MetadataLibraryImports(metadata), StateLibraryCopies(state), Dispatchers.Default)
        val path = InstrumentationRegistry.getArguments().getString("extendedLibraryDb")
        assumeTrue("extendedLibraryDb is not supplied", path != null)
        importCopy = pull(path!!, File(root, "import.db"))
        oracle = SQLiteDatabase.openDatabase(pull(path, File(root, "oracle.db")).path, null, SQLiteDatabase.OPEN_READONLY)
        runBlocking {
            val selected = state.select(LibraryLocation.Local("extended.documents", "tree-${UUID.randomUUID()}"))
            assertNotNull(metadata.importSnapshot(selected.token, importCopy!!))
            assertTrue(metadata.selectReadColumn(metadata.currentImport()!!, CustomColumnId(1, "#read_status")))
        }
    }

    @After
    fun tearDown() {
        oracle?.close()
        database.close()
        context.deleteDatabase(databaseName)
        root.deleteRecursively()
    }

    private fun pull(path: String, target: File): File {
        val descriptor = InstrumentationRegistry.getInstrumentation().uiAutomation.executeShellCommand("cat $path")
        ParcelFileDescriptor.AutoCloseInputStream(descriptor).use { input -> target.outputStream().use { input.copyTo(it) } }
        assertTrue("not an SQLite file: $path", target.length() > 100 && target.inputStream().use { s -> ByteArray(15).also { s.read(it) } }.decodeToString() == "SQLite format 3")
        return target
    }

    private fun rows(sql: String): List<List<String?>> = oracle!!.rawQuery(sql, null).use { c ->
        buildList { while (c.moveToNext()) add((0 until c.columnCount).map { if (c.isNull(it)) null else c.getString(it) }) }
    }

    private fun idsOf(sql: String): Set<Long> = rows(sql).map { it[0]!!.toLong() }.toSet()

    private fun query(request: LibraryRequest) = runBlocking { service.query(request) }
    private fun books(request: LibraryRequest) = query(request) as LibraryQueryResult.Books
    private fun folders(request: LibraryRequest) = query(request) as LibraryQueryResult.Folders

    private fun everything(request: LibraryRequest, pageSize: Int): List<BookRow> {
        val first = books(request.copy(offset = 0, pageSize = pageSize))
        return buildList {
            addAll(first.rows)
            while (size < first.total) {
                val page = books(request.copy(offset = size, pageSize = pageSize))
                assertTrue(page.rows.isNotEmpty())
                addAll(page.rows)
            }
        }
    }

    private val total get() = rows("SELECT count(*) FROM books")[0][0]!!.toInt()

    @Test
    fun pagingIsStableAndCoversEveryBookExactlyOnce() {
        assertEquals(286, total)
        for (sort in listOf(BookSort.Default, BookSort(BookSortKey.TITLE, true), BookSort(BookSortKey.RATING, false))) {
            val single = everything(LibraryRequest(sort = sort, pageSize = 1000), 1000)
            val paged = everything(LibraryRequest(sort = sort, pageSize = 20), 20)
            assertEquals(total, single.size)
            assertEquals("each book once", total, single.map { it.key.sourceId }.toSet().size)
            assertEquals("pages concatenate to the full order", single.map { it.key }, paged.map { it.key })
        }
        val last = books(LibraryRequest(offset = 280, pageSize = 20))
        assertEquals(6, last.rows.size)
        assertEquals(total, last.total)
    }

    @Test
    fun sortsPlaceMissingValuesLastAndKeepOrderMonotonic() {
        val ratings = rows("SELECT b.id, r.rating FROM books b LEFT JOIN books_ratings_link l ON l.book=b.id LEFT JOIN ratings r ON r.id=l.rating")
            .associate { it[0]!!.toLong() to it[1]?.toInt() }
        assertTrue("library has rated and unrated books", ratings.values.any { it == null } && ratings.values.any { it != null })
        for (ascending in listOf(true, false)) {
            val sequence = everything(LibraryRequest(sort = BookSort(BookSortKey.RATING, ascending), pageSize = 1000), 1000).map { ratings[it.key.sourceId] }
            val firstNull = sequence.indexOfFirst { it == null }
            assertTrue("missing ratings sort last either direction", sequence.drop(firstNull).all { it == null })
            val present = sequence.filterNotNull()
            assertEquals(if (ascending) present.sorted() else present.sortedDescending(), present)
        }
        val titles = rows("SELECT id, title FROM books").associate { it[0]!!.toLong() to it[1]!! }
        val byTitle = everything(LibraryRequest(sort = BookSort(BookSortKey.TITLE, true), pageSize = 1000), 1000).map { titles.getValue(it.key.sourceId) }
        assertEquals(byTitle.sortedWith { a, b -> collator.compare(a, b) }, byTitle)
        val added = rows("SELECT id, strftime('%s', timestamp) FROM books").associate { it[0]!!.toLong() to it[1]!!.toLong() }
        val newest = everything(LibraryRequest(pageSize = 1000), 1000).map { added.getValue(it.key.sourceId) }
        assertEquals(newest.sortedDescending(), newest)
    }

    @Test
    fun tagSeriesAndColumnFoldersMatchTheLibrary() {
        val added = rows("SELECT id, strftime('%s', timestamp) FROM books").associate { it[0]!!.toLong() to it[1]!!.toLong() }
        fun check(categorization: Categorization, membership: String) {
            val expected = rows(membership).groupBy({ it[1]!! }, { it[0]!!.toLong() })
            val noValue = total - expected.values.flatten().toSet().size
            val result = folders(LibraryRequest(categorization = categorization, pageSize = 1000))
            val names = result.rows.map { it.key.name }
            assertEquals("$categorization folders", expected.keys + if (noValue > 0) setOf(null) else emptySet(), names.toSet())
            if (noValue > 0) assertNull("the no-value folder is last", names.last())
            val named = names.filterNotNull()
            assertEquals(named.sortedWith { a, b -> collator.compare(a, b) }, named)
            result.rows.forEach { folder ->
                val members = expected[folder.key.name]?.toSet()
                assertEquals("$categorization ${folder.key.name} count", members?.size ?: noValue, folder.bookCount)
                if (members != null) {
                    assertEquals(members.maxOf { added.getValue(it) }, added.getValue(folder.representative.key.sourceId))
                    assertTrue(folder.representative.key.sourceId in members)
                }
            }
            val inside = result.rows.first().key
            assertEquals(result.rows.first().bookCount, books(LibraryRequest(categorization = categorization, folder = inside, pageSize = 1000)).total)
        }
        check(Categorization.Tags, "SELECT l.book, t.name FROM books_tags_link l JOIN tags t ON t.id=l.tag")
        check(Categorization.Series, "SELECT l.book, s.name FROM books_series_link l JOIN series s ON s.id=l.series")
        check(Categorization.Column(CustomColumnId(2, "#topic")),
            "SELECT l.book, v.value FROM books_custom_column_2_link l JOIN custom_column_2 v ON v.id=l.value")
        check(Categorization.Column(CustomColumnId(3, "#shelf")),
            "SELECT l.book, v.value FROM books_custom_column_3_link l JOIN custom_column_3 v ON v.id=l.value")
        val unsupported = query(LibraryRequest(categorization = Categorization.Column(CustomColumnId(6, "#formula")), pageSize = 10))
        assertEquals(LibraryQueryResult.Unavailable(LibraryProblem.CATEGORY_COLUMN_INVALID), unsupported)
    }

    @Test
    fun seriesFolderOrdersBySeriesIndexAscendingWithFractions() {
        val index = rows("SELECT id, series_index FROM books").associate { it[0]!!.toLong() to it[1]!!.toDouble() }
        val result = folders(LibraryRequest(categorization = Categorization.Series, pageSize = 100))
        assertTrue(result.rows.any { it.key.name != null })
        result.rows.filter { it.key.name != null }.forEach { folder ->
            val request = LibraryRequest(categorization = Categorization.Series, folder = folder.key,
                sort = BookSort.defaultFor(Categorization.Series, folder.key), pageSize = 1000)
            val order = books(request).rows.map { index.getValue(it.key.sourceId) }
            assertEquals(order.sorted(), order)
        }
    }

    @Test
    fun readFiltersTreatEmptyAndNoAsUnreadForTheConfiguredBooleanColumn() {
        val read = idsOf("SELECT book FROM custom_column_1 WHERE value=1")
        val no = idsOf("SELECT book FROM custom_column_1 WHERE value=0")
        val everyBook = idsOf("SELECT id FROM books")
        val empty = everyBook - read - no
        assertTrue("library has yes, no and empty values", read.isNotEmpty() && no.isNotEmpty() && empty.isNotEmpty())
        fun matches(filter: ReadFilter) = everything(LibraryRequest(filters = LibraryFilters(reads = setOf(filter)), pageSize = 1000), 1000)
        assertEquals(read, matches(ReadFilter.READ).map { it.key.sourceId }.toSet())
        // R13: an empty value is unread, like "no".
        assertEquals(no + empty, matches(ReadFilter.UNREAD).map { it.key.sourceId }.toSet())
        assertEquals(everyBook, books(LibraryRequest(filters = LibraryFilters(reads = ReadFilter.entries.toSet()), pageSize = 1000))
            .rows.map { it.key.sourceId }.toSet())
        assertTrue(everything(LibraryRequest(pageSize = 1000), 1000).all { it.read != null })
    }

    @Test
    fun searchScopesMatchLiteralSubstringsOfTheirFields() {
        val titles = rows("SELECT id, title FROM books").associate { it[0]!!.toLong() to it[1]!! }
        fun ids(request: LibraryRequest) = everything(request.copy(pageSize = 1000), 1000).map { it.key.sourceId }.toSet()
        val title = ids(LibraryRequest(search = "tales harbor", searchScope = SearchScope.Title, pageSize = 1000))
        assertEquals(titles.filterValues { it.lowercase().let { t -> "tales" in t && "harbor" in t } }.keys, title)
        assertTrue(title.isNotEmpty())
        val tag = ids(LibraryRequest(search = "历史", searchScope = SearchScope.Tags, pageSize = 1000))
        assertEquals(idsOf("SELECT l.book FROM books_tags_link l JOIN tags t ON t.id=l.tag WHERE t.name LIKE '%历史%'"), tag)
        val series = ids(LibraryRequest(search = "星河", searchScope = SearchScope.Series, pageSize = 1000))
        assertEquals(idsOf("SELECT l.book FROM books_series_link l JOIN series s ON s.id=l.series WHERE s.name LIKE '%星河%'"), series)
        val authors = ids(LibraryRequest(search = "alice", searchScope = SearchScope.Authors, pageSize = 1000))
        assertEquals(idsOf("SELECT l.book FROM books_authors_link l JOIN authors a ON a.id=l.author WHERE a.name LIKE '%alice%'"), authors)
        val shelf = rows("SELECT value FROM custom_column_3 LIMIT 1")[0][0]!!
        val column = ids(LibraryRequest(search = shelf, searchScope = SearchScope.Column(CustomColumnId(3, "#shelf")), pageSize = 1000))
        assertEquals(idsOf("SELECT l.book FROM books_custom_column_3_link l JOIN custom_column_3 v ON v.id=l.value WHERE v.value LIKE '%$shelf%'"), column)
        val all = ids(LibraryRequest(search = "历史", pageSize = 1000))
        assertTrue("whole-library search includes tag matches", all.containsAll(tag))
        // A wildcard or SQL fragment is plain text, not an expression.
        assertTrue(ids(LibraryRequest(search = "%", pageSize = 1000)).isEmpty())
        assertTrue(ids(LibraryRequest(search = "' OR 1=1 --", pageSize = 1000)).isEmpty())
        // Searching flattens a categorized view to books and ignores the folder level.
        val flattened = books(LibraryRequest(search = "历史", categorization = Categorization.Tags, pageSize = 1000))
        assertEquals(all.size, flattened.total)
    }

    @Test
    fun rowsCarryDefaultFormatAuthorsAndCoverFromTheSource() {
        val formats = rows("SELECT book, format, uncompressed_size FROM data").groupBy({ it[0]!!.toLong() }, { it[1]!! to it[2]!!.toLong() })
        val authors = idsOf("SELECT DISTINCT book FROM books_authors_link")
        val covers = idsOf("SELECT id FROM books WHERE has_cover=1")
        val all = everything(LibraryRequest(pageSize = 1000), 1000)
        assertTrue(all.any { it.defaultFormat == null } && all.any { it.authors.isEmpty() } && all.any { !it.hasCover })
        all.forEach { row ->
            val id = row.key.sourceId
            val own = formats[id].orEmpty()
            val expected = own.firstOrNull { it.first == "EPUB" } ?: own.minByOrNull { it.first }
            assertEquals("default format of book $id", expected?.first, row.defaultFormat?.format?.value)
            assertEquals(expected?.second, row.defaultFormat?.sizeBytes)
            assertEquals(expected == null, row.noFormat == NoFormatReason.NO_FORMAT)
            assertEquals(id in authors, row.authors.isNotEmpty())
            assertEquals(id in covers, row.hasCover)
            assertFalse(row.downloaded)
        }
        val formatFilter = LibraryFilters(formats = setOf(BookFormat.parse("PDF")))
        assertEquals(idsOf("SELECT DISTINCT book FROM data WHERE format='PDF'"),
            everything(LibraryRequest(filters = formatFilter, pageSize = 1000), 1000).map { it.key.sourceId }.toSet())
    }

    @Test
    fun representativeScaleQueryTimesAreLogged() {
        val cold = System.nanoTime()
        books(LibraryRequest(pageSize = 20))
        val firstMs = (System.nanoTime() - cold) / 1_000_000
        val timings = listOf(
            "search" to LibraryRequest(search = "tales harbor", pageSize = 20),
            "tag-folders" to LibraryRequest(categorization = Categorization.Tags, pageSize = 20),
            "title-sort" to LibraryRequest(sort = BookSort(BookSortKey.TITLE, true), pageSize = 20),
            "read-filter" to LibraryRequest(filters = LibraryFilters(reads = setOf(ReadFilter.UNREAD)), pageSize = 20),
        ).map { (name, request) ->
            val start = System.nanoTime()
            query(request)
            "$name=${(System.nanoTime() - start) / 1_000_000}ms"
        }
        android.util.Log.i("LibraryQueryReference", "books=$total first_query_with_index_build_ms=$firstMs warm: ${timings.joinToString(" ")}")
    }
}
