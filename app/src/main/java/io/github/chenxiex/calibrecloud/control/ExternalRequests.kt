package io.github.chenxiex.calibrecloud.control

import java.security.MessageDigest

/**
 * The request format of the external control interface (R37), shared by both entries: a URI
 * `<scheme>://<operation>?<parameters>` carried as the data of a broadcast to [ExternalControlReceiver]
 * (stay in the reader) or of a `VIEW` intent to [ExternalControlActivity] (open this app, or confirm a
 * registration). Operations are told apart by name; a new operation adds a name and never changes the
 * parameters of an existing one, and an unknown name is rejected.
 */
object ExternalProtocol {
    const val MARK_READ = "mark_read"
    const val MARK_UNREAD = "mark_unread"
    const val REGISTER = "register"

    /** The caller's secret, generated by the caller and registered once (Q87, Q92). */
    const val TOKEN = "token"

    /** The file name the reader sees, as this app gave it (R28); a path keeps only its last segment. */
    const val FILE = "file"

    /** The caller's name shown in the registration prompt; it cannot be verified. */
    const val NAME = "name"

    private val TOKEN_FORM = Regex("[A-Za-z0-9_-]{32,128}")
    private const val MAX_NAME = 64

    /** Reads a request from the URI's operation (its host) and parameters; null fields are absent. */
    fun parse(operation: String?, parameter: (String) -> String?): ParsedRequest {
        val token = parameter(TOKEN)?.takeIf { TOKEN_FORM.matches(it) }
        return when (operation) {
            MARK_READ, MARK_UNREAD -> {
                val file = parameter(FILE)?.substringAfterLast('/')?.takeIf { it.isNotBlank() }
                if (token == null || file == null) ParsedRequest.Malformed
                else ParsedRequest.Valid(ExternalRequest.MarkReadStatus(operation == MARK_READ, token, file))
            }
            REGISTER -> {
                val name = parameter(NAME)?.trim()?.takeIf { name ->
                    name.isNotEmpty() && name.length <= MAX_NAME && name.none { Character.isISOControl(it) }
                }
                if (token == null || name == null) ParsedRequest.Malformed else ParsedRequest.Valid(ExternalRequest.Register(name, token))
            }
            else -> ParsedRequest.UnknownOperation
        }
    }

    /** Only this hash is stored; requests are matched by it. */
    fun tokenHash(token: String): String =
        MessageDigest.getInstance("SHA-256").digest(token.toByteArray(Charsets.UTF_8)).joinToString("") { "%02x".format(it) }
}

sealed interface ExternalRequest {
    val token: String

    /** Marks the book the reader knows as [file] read ([target] true) or unread, like the page's button. */
    data class MarkReadStatus(val target: Boolean, override val token: String, val file: String) : ExternalRequest {
        override fun toString() = "MarkReadStatus(target=$target)"
    }

    /** Asks the user to allow the caller [name] with [token]. */
    data class Register(val name: String, override val token: String) : ExternalRequest {
        override fun toString() = "Register"
    }
}

sealed interface ParsedRequest {
    data class Valid(val request: ExternalRequest) : ParsedRequest
    data object UnknownOperation : ParsedRequest
    data object Malformed : ParsedRequest
}
